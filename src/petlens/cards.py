"""Model card, dataset card and attribution list (Step 17): ``make cards``.

Everything is generated, never hand-edited, so the cards can't drift from the model and
data they describe:

- ``MODEL_CARD.md`` from the run the app serves (the registry's champion, or the latest
  run) and its gate result.
- ``DATASET_CARD.md`` from the latest committed manifest.
- ``ATTRIBUTION.md`` from the same manifest: the Oxford-IIIT Pet citation once, then one
  line per Commons or Openverse photo with its author, licence and link.
"""

from __future__ import annotations

import json
import logging
from collections import Counter
from pathlib import Path
from typing import Any

from petlens.data.catalog import REPO_DATA_DIR, load_breeds
from petlens.data.manifest import ManifestRow, read_manifest

log = logging.getLogger(__name__)

REPO = REPO_DATA_DIR.parent
SPLITS = [
    "train",
    "val",
    "calibration",
    "rw_calibration",
    "test_in_domain",
    "test_unseen_source",
    "test_domestic",
    "test_unknown",
    "excluded",
]
TEST_NAMES = {
    "test_in_domain": "Same sources as training",
    "test_unseen_source": "Sources never trained on",
    "test_domestic": "Ordinary cats (no breed)",
    "test_unknown": "Breeds the model doesn't know",
    "golden": "Golden set (frozen, hand-checked)",
}
OXFORD_CITATION = (
    "O. M. Parkhi, A. Vedaldi, A. Zisserman and C. V. Jawahar, *Cats and Dogs*, IEEE "
    "CVPR 2012. The Oxford-IIIT Pet Dataset, CC BY-SA 4.0; image copyright remains with "
    "the original owners."
)


def latest_manifest(repo_data: Path = REPO_DATA_DIR) -> tuple[str, list[ManifestRow]]:
    version = (repo_data / "manifests" / "LATEST").read_text(encoding="utf-8").strip()
    return version, read_manifest(repo_data / "manifests" / f"{version}.parquet")


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


# --- dataset card -------------------------------------------------------------------


def dataset_card(version: str, rows: list[ManifestRow]) -> str:
    breeds = load_breeds()
    split = Counter(r.split or "" for r in rows)
    sources = Counter(r.source for r in rows)
    origins = Counter(r.label_origin for r in rows)
    flags = Counter(f for r in rows for f in r.flags)
    licences = Counter(r.licence for r in rows)
    lines = [
        f"# Dataset card: {version}",
        "",
        "_Generated by `make cards` from `data/manifests/"
        f"{version}.parquet`. Do not edit by hand._",
        "",
        "## What it is",
        "",
        "Photos of cats and dogs labelled with the breed they look like, for training and "
        "testing PetLens. The manifest (committed) lists every photo with its source, "
        "licence, author, label origin, quality flags and split; the images themselves are "
        "downloaded by `make data` and are never committed.",
        "",
        f"- Photos: **{len(rows)}** ({len(rows) - split.get('excluded', 0)} usable)",
        f"- Groups (near-duplicates and same-animal photos kept in one split): "
        f"{len({r.group_id for r in rows if r.group_id})}",
        f"- Cat classes trained: {len(breeds.training_classes('cat'))}, dog classes: "
        f"{len(breeds.training_classes('dog'))}",
        "",
        "## Sources",
        "",
        "| Source | Photos |",
        "| --- | ---: |",
        *[f"| {s} | {n} |" for s, n in sources.most_common()],
        "",
        "## Where labels come from",
        "",
        "| Label origin | Photos |",
        "| --- | ---: |",
        *[f"| {o} | {n} |" for o, n in origins.most_common()],
        "",
        "Oxford labels are expert annotations. Commons labels come from the category a "
        "photo was filed in, which is noisy, so Commons photos are screened (image quality, "
        "the local VLM's tags, and my swipe reviews) before they can be trained on. Labels "
        "with origin `me` are ones I reviewed.",
        "",
        "## Splits",
        "",
        "Splits are made per group, so the same animal or a near-duplicate never sits on "
        "both sides. `test_unseen_source` only holds sources the model never trained on; "
        "`test_domestic` holds ordinary cats, to count false breed claims; `test_unknown` "
        "holds breeds the model doesn't know, to check it says so.",
        "",
        "| Split | Photos |",
        "| --- | ---: |",
        *[f"| {s} | {split.get(s, 0)} |" for s in SPLITS if split.get(s)],
        "",
        f"Per-breed counts: [`data/manifests/{version}.md`](data/manifests/{version}.md).",
        "",
        "## Quality flags",
        "",
        "| Flag | Photos |",
        "| --- | ---: |",
        *([f"| {f} | {n} |" for f, n in flags.most_common()] or ["| none | 0 |"]),
        "",
        "## Licences",
        "",
        "| Licence | Photos |",
        "| --- | ---: |",
        *[f"| {lic} | {n} |" for lic, n in licences.most_common()],
        "",
        "Every photo's author and link is in [ATTRIBUTION.md](ATTRIBUTION.md).",
        "",
        "## Known gaps and biases",
        "",
        "- Breeds with few openly licensed photos (several Commons categories are nearly "
        "empty) have thin training data and wider error bars.",
        "- Commons and Oxford photos are mostly well lit and posed; webcam frames are "
        "darker and blurrier, which is why training adds webcam-style degradation.",
        '- "Looks like" is a visual judgement. A label says which breed a photo resembles, '
        "not the animal's pedigree.",
        "",
    ]
    return "\n".join(lines)


# --- model card ---------------------------------------------------------------------


def serving_info(models_dir: Path) -> dict[str, Any] | None:
    from petlens.models.registry import serving_run

    try:
        path = serving_run(models_dir)
    except (FileNotFoundError, SystemExit, ValueError):
        return None
    info: dict[str, Any] = json.loads((path / "metrics.json").read_text(encoding="utf-8"))
    return info


def champion_gate() -> dict[str, Any] | None:
    try:
        from petlens.db.session import session_scope
        from petlens.models.registry import champion

        with session_scope() as s:
            best = champion(s)
            return dict(best.gate) if best and best.gate else None
    except Exception as exc:  # no database: the card goes without the gate
        log.warning("registry unavailable (%s)", type(exc).__name__)
        return None


def metrics_table(info: dict[str, Any]) -> list[str]:
    out = [
        "| Species | Test set | Top-1 | False breed claims | Unknown breeds rejected |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for species, mt in info.get("metrics", {}).items():
        if not isinstance(mt, dict) or "tests" not in mt:
            continue
        pol = mt.get("policy") or {}
        for test, t in mt["tests"].items():
            claims = pol.get(test, {}).get("false_breed_claim_rate")
            rejected = pol.get(test, {}).get("unknown_rejection_rate")
            out.append(
                f"| {species} | {TEST_NAMES.get(test, test)} | {pct(t['calibrated']['top1'])} "
                f"| {pct(claims)} | {pct(rejected)} |"
            )
    return out


def model_card(info: dict[str, Any] | None, gate: dict[str, Any] | None) -> str:
    lines = [
        "# Model card: PetLens breed suggester",
        "",
        "_Generated by `make cards` from the run the app serves. Do not edit by hand._",
        "",
        "## Intended use",
        "",
        "Suggest which breed a cat or dog in a photo, short clip or webcam frame looks most "
        "like, with a calibrated confidence, for a personal, local-only app. It answers "
        '"domestic cat, no clear breed" for ordinary cats and "not sure" when a photo '
        "doesn't look like anything it was trained on.",
        "",
        "**Not for:** proving pedigree, pricing or selling animals, health or behaviour "
        "judgements, or anything about people (people in frames are blurred and never "
        "classified).",
        "",
        "## How it works",
        "",
        "RF-DETR finds each animal; the crop goes through a DINOv2 backbone (frozen or with "
        "its last blocks fine-tuned); a per-species head gives breed probabilities, "
        "temperature-scaled on a calibration split. A kNN distance to the training "
        "embeddings flags photos unlike anything seen. A decision policy, tuned on held-out "
        "data, turns that into accept, no clear breed, or review.",
        "",
    ]
    if info is None:
        lines += [
            "## This machine",
            "",
            "No trained run was found when this card was generated, so it has no numbers. "
            "Run `make train` (and `make register promote`), then `make cards`.",
            "",
        ]
    else:
        cfg = info.get("metrics", {}).get("policy_config") or {}
        lines += [
            "## The serving run",
            "",
            f"- Run: `{info.get('run_id')}`",
            f"- Dataset version: `{info.get('dataset_version')}` "
            "(see [DATASET_CARD.md](DATASET_CARD.md))",
            f"- Backbone: `{info.get('embedding_model')}`",
            f"- Weights SHA-256: `{str(info.get('weights_sha256', ''))[:16]}...`",
            "",
            "## Results",
            "",
            *metrics_table(info),
            "",
        ]
        if cfg:
            lines += [
                "Decision thresholds (tuned on held-out data, stored with the run):",
                "",
                "```json",
                json.dumps(cfg, indent=2, sort_keys=True),
                "```",
                "",
            ]
    if gate:
        verdict = "passed" if gate.get("passed") else "failed"
        lines += [
            "## Promotion gate",
            "",
            f"This run became the champion after the gate {verdict}: "
            "a paired bootstrap over the same photos (golden set and unseen sources), no "
            "breed's recall falling by more than 10 points, and no rise in false breed claims "
            "on ordinary cats.",
            "",
            "```json",
            json.dumps(gate.get("numbers", gate), indent=2, sort_keys=True)[:4000],
            "```",
            "",
        ]
    lines += [
        "## Limitations",
        "",
        "- Mixed-breed dogs get the breed they look most like; that is a resemblance, not "
        "ancestry.",
        "- Look-alike pairs (Ragdoll and Birman, British Shorthair and Russian Blue) are the "
        "most common mistakes; the page shows both when the gap is small.",
        "- Webcam frames in poor light score lower than photos; the live page averages over "
        "several frames to steady the answer.",
        "- Trained only on openly licensed photos: breeds with few such photos are less reliable.",
        "",
    ]
    return "\n".join(lines)


# --- attribution --------------------------------------------------------------------


def attribution(version: str, rows: list[ManifestRow]) -> str:
    lines = [
        "# Attribution",
        "",
        f"_Generated by `make cards` from dataset version `{version}`. Photos are not in "
        "this repository; they are downloaded by `make data` from the sources below._",
        "",
        "## Oxford-IIIT Pet Dataset",
        "",
        OXFORD_CITATION,
        "",
    ]
    by_source: dict[str, list[ManifestRow]] = {}
    for r in rows:
        if r.source != "oxford" and r.label_origin != "me" and r.split != "excluded":
            by_source.setdefault(r.source, []).append(r)
    titles = {"commons": "Wikimedia Commons", "openverse": "Openverse"}
    for source, items in sorted(by_source.items()):
        lines += [f"## {titles.get(source, source)}", ""]
        for r in sorted(items, key=lambda r: r.source_ref):
            who = r.author or r.uploader or "Unknown author"
            lines.append(f"- {who}, {r.licence}: <{r.source_ref}>")
        lines.append("")
    return "\n".join(lines)


def main(models_dir: Path | None = None, out_dir: Path = REPO) -> list[Path]:
    from petlens.config import get_settings

    version, rows = latest_manifest()
    info = serving_info(models_dir or get_settings().models_dir)
    written = {
        out_dir / "DATASET_CARD.md": dataset_card(version, rows),
        out_dir / "MODEL_CARD.md": model_card(info, champion_gate() if info else None),
        out_dir / "ATTRIBUTION.md": attribution(version, rows),
    }
    for path, body in written.items():
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path.name}")
    return list(written)


if __name__ == "__main__":
    main()
